export function LandingFeatures() {
  const [visible, setVisible] = useState<number[]>([]);
  const sectionRef = useRef<HTMLElement>(null);

  useEffect(() => {
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          const timer = setInterval(() => {
            setVisible((prev) => {
              if (prev.length >= features.length) {
                clearInterval(timer);
                return prev;
              }
              return [...prev, prev.length];
            });
          }, 100);
        }
      },
      { threshold: 0.1 },
    );

    if (sectionRef.current) observer.observe(sectionRef.current);
    return () => observer.disconnect();
  }, []);

  return (
    <section
      ref={sectionRef}
      className="relative z-10 border-t border-glass-border bg-surface py-24"
    >
      <div className="mx-auto max-w-6xl px-6">
        <div className="section-header">
          <div className="section-badge">Features</div>
          <h2 className="section-title">
            Everything you need to
            <br />
            <span className="text-gradient">ship better code</span>
          </h2>
          <p className="section-subtitle">
            A complete version control platform designed for modern development
            teams. No complexity, just productivity.
          </p>
        </div>

        <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {features.map((feature, index) => (
            <div
              key={feature.title}
              className={`glass-card p-6 transition-all duration-500 ${
                visible.includes(index)
                  ? "opacity-100 translate-y-0"
                  : "opacity-0 translate-y-8"
              }`}
              style={{ transitionDelay: `${index * 100}ms` }}
            >
              <div className="mb-4 flex size-10 items-center justify-center rounded-xl bg-accent-glow text-accent">
                {feature.icon}
              </div>
              <h3 className="mb-2 text-base font-semibold text-primary">
                {feature.title}
              </h3>
              <p className="text-sm leading-relaxed text-muted">
                {feature.description}
              </p>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
}
